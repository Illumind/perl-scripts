def android_escape(s):
    s = escape(s)
    return s.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')

base = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res")
for idx, folder in enumerate(["values", "values-uk", "values-pl"]):
    os.makedirs(os.path.join(base, folder), exist_ok=True)
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Згенеровано tools/gen_strings.py — редагуйте там. -->", "<resources>"]
    for k, v in S.items():
        attr = ' translatable="false"' if k == "app_name" and idx == 0 else ""
        if "%" in v[idx] and "%1$" not in v[idx]:
            attr += ' formatted="false"'  # літеральний % (напр. "80%") — не плейсхолдер
        if k == "app_name" and idx > 0:
            continue
        lines.append(f'    <string name="{k}"{attr}>{android_escape(v[idx])}</string>')
    lines.append("</resources>\n")
    with open(os.path.join(base, folder, "strings.xml"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
print(f"{len(S)} strings × 3 languages")
